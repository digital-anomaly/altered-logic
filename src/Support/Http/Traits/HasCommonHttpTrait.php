    /**
     * Send a request, and stream the response.
     *
     * @param string              $method The HTTP method to send the request with.
     * @param string              $url    The url to send the request to.
     * @param array<string,mixed> $params The GET parameters to send with the request.
     * @return HttpStreamInterface
     */
    abstract private function streamSend(string $method, string $url, array $params = []): HttpStreamInterface;





    /**
     * Record the httpTxn.
     *
     * @param HttpTxnDTO $httpTxn The httpTxnDTO to record.
     * @return void
     */
    private function setHttpTxn(HttpTxnDTO $httpTxn): void
    {
        $this->httpTxn = $httpTxn;
    }

    /**
     * Build an HttpTxnDTO representing the current state of the client.
     *
     * This is useful when streaming responses (as the stream is what's returned originally. e.g. ->streamPost()).
     *
     * @return HttpTxnDTO|null
     */
    public function httpTxn(): ?HttpTxnDTO
    {
        return $this->httpTxn;
    }
